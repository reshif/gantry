// Regenerates src/seed.data.ts from the legacy G.seed(): node scripts/gen-seed.mjs
// The legacy seed is evaluated once under a fixed clock; timestamps are shifted at runtime by devSeed(now).
import fs from "node:fs";
import path from "node:path";
import { loadLegacy } from "./legacy-eval.mjs";

const { G, anchor } = loadLegacy();
const state = JSON.parse(JSON.stringify(G.store.get()));
state.session = null;
const data = {
  anchor,
  state,
  catalog: { stations: G.STATIONS, gates: G.GATES, bays: G.BAYS, classes: G.CLASSES, roles: G.ROLES, actions: G.ACTIONS },
  integrationCategories: G.INTEGRATION_CATEGORIES,
  notifyEvents: G.NOTIFY_EVENTS,
};
const json = JSON.stringify(data);
const out = `// GENERATED by scripts/gen-seed.mjs from legacy/js (G.seed). Do not edit by hand.
// Dev/demo org only. Timestamps are relative to SEED_ANCHOR; devSeed(now) shifts them.
export const SEED_ANCHOR = ${anchor};
export const SEED_JSON: string = ${JSON.stringify(json)};
`;
fs.writeFileSync(path.resolve(import.meta.dirname, "../src/seed.data.ts"), out);
console.log("seed bytes", json.length);
